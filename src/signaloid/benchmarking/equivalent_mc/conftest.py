# ---------------------------------------------------------------------------
# Synthetic UxHw-trace database builder: shared test support.
#
# Replaces the committed binary fixtures (uxhw-reference.db, uxhw-under-test.db,
# tracing.db), which also scrubs the internal absolute source path they embedded
# in Expression_DeclarationFileName. The data is synthetic: each (expression,
# configuration) carries a Gaussian quantised to the configuration's atom count,
# exported to the Ux string format UxHw emits and parsed back by the production
# loaders (``equivalent_mc/load.py``). Tests assert pipeline structure, not
# specific numbers, so fidelity to the original captured traces is unnecessary.
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class SyntheticUxhwExpression:
    """One traced output expression in a synthetic UxHw database."""

    name: str
    value_id: str
    centre: float
    scale: float
    subprogram: str = "main"
    file_name: str = "main.c"
    line_number: int = 95


@dataclass(frozen=True)
class SyntheticUxhwConfig:
    """One emulator configuration — a row of ``Emulator_Execution_Info``."""

    ur_type: str
    ur_order: int
    correlation: str  # "Disabled" or "Autocorrelation"

    @property
    def ur_order_core_library(self) -> int:
        # UxHw also counts the 3 internal sentinel Diracs it keeps for
        # Athens-style representations, so the core-library order is N + 3.
        return self.ur_order + 3


def gaussian_ux_string(centre: float, scale: float, n_atoms: int, ur_type: str) -> str:
    """
    Build a UxHw-format Ux string for a Gaussian quantised to ``n_atoms``.

    Positions span +/- 3.5 standard deviations around ``centre`` with Gaussian
    masses. The result is exported through the production
    :meth:`DistributionalValue.export` path so it round-trips through
    :meth:`DistributionalValue.parse`.

    Args:
        centre: Mean of the Gaussian.
        scale: Standard deviation of the Gaussian.
        n_atoms: Number of quantisation atoms (positions).
        ur_type: Representation type name to stamp on the Ux string.

    Returns:
        The Ux-format string for the quantised Gaussian.
    """
    positions = np.linspace(centre - 3.5 * scale, centre + 3.5 * scale, n_atoms)
    masses = np.exp(-0.5 * ((positions - centre) / scale) ** 2)
    masses = masses / masses.sum()
    distribution = DistributionalValue.from_weighted_samples(positions, masses)
    distribution.UR_type = STRING_TO_CORE_REPRESENTATION[ur_type]
    return str(distribution)


def build_uxhw_database(
    db_path: str,
    table_name: str,
    expressions: list[SyntheticUxhwExpression],
    configurations: list[SyntheticUxhwConfig],
) -> None:
    """
    Write a synthetic traced-UxHw SQLite database to ``db_path``.

    Creates ``Emulator_Execution_Info`` (one row per configuration) and
    ``table_name`` (one row per expression x configuration, carrying a Ux
    string), matching the schema the production ``_load_uxhw`` loader reads.

    Args:
        db_path: Path to write the SQLite database to.
        table_name: Name of the traced-values table to create.
        expressions: Traced output expressions to populate.
        configurations: Emulator configurations to populate.
    """
    with closing(sqlite3.connect(db_path)) as connection:
        cursor = connection.cursor()
        cursor.execute("""
            CREATE TABLE Emulator_Execution_Info (
                Execution_ID INTEGER PRIMARY KEY AUTOINCREMENT,
                Host_Date TEXT,
                Host_Microseconds INTEGER,
                UR_Type TEXT,
                UR_Order INTEGER,
                UR_Order_CoreLibrary INTEGER,
                CorrelationTracking_Status TEXT,
                Host_UserTimeElapsedWallClock REAL,
                EmulatedCPU_DynCnt INTEGER
            )
            """)
        cursor.execute(f"""
            CREATE TABLE "{table_name}" (
                ValueId TEXT,
                Expression_Name TEXT,
                Expression_Subprogram TEXT,
                Expression_DeclarationFileName TEXT,
                Expression_DeclarationLineNumber INTEGER,
                Host_Date TEXT,
                Host_Microseconds INTEGER,
                Execution_Info_Table_ID INTEGER,
                UR_Type TEXT,
                UR_Order INTEGER,
                UR_Order_CoreLibrary INTEGER,
                Assignment_Line INTEGER,
                Assignment_Index INTEGER,
                Particle_Value REAL,
                Dist_Value TEXT
            )
            """)
        for execution_id, config in enumerate(configurations, start=1):
            cursor.execute(
                "INSERT INTO Emulator_Execution_Info ("
                "Execution_ID, Host_Date, Host_Microseconds, UR_Type, UR_Order, "
                "UR_Order_CoreLibrary, CorrelationTracking_Status, "
                "Host_UserTimeElapsedWallClock, EmulatedCPU_DynCnt) "
                "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)",
                (
                    execution_id,
                    "1970-01-01",
                    0,
                    config.ur_type,
                    config.ur_order,
                    config.ur_order_core_library,
                    config.correlation,
                    0.0,
                    0,
                ),
            )
            for expression in expressions:
                ux_string = gaussian_ux_string(
                    expression.centre,
                    expression.scale,
                    config.ur_order,
                    config.ur_type,
                )
                cursor.execute(
                    f'INSERT INTO "{table_name}" ('
                    "ValueId, Expression_Name, Expression_Subprogram, "
                    "Expression_DeclarationFileName, "
                    "Expression_DeclarationLineNumber, Host_Date, "
                    "Host_Microseconds, Execution_Info_Table_ID, UR_Type, "
                    "UR_Order, UR_Order_CoreLibrary, Assignment_Line, "
                    "Assignment_Index, Particle_Value, Dist_Value) "
                    "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
                    (
                        expression.value_id,
                        expression.name,
                        expression.subprogram,
                        expression.file_name,
                        expression.line_number,
                        "1970-01-01",
                        0,
                        execution_id,
                        config.ur_type,
                        config.ur_order,
                        config.ur_order_core_library,
                        expression.line_number,
                        1,
                        expression.centre,
                        ux_string,
                    ),
                )
        connection.commit()
